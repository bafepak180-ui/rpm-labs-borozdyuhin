# Перевод температуры из градусов Цельсия в Фаренгейты и Кельвины

# Ввод температуры с проверкой на число
try:
    celsius = float(input("Введите температуру в °C: "))
except ValueError:
    print("Ошибка: нужно ввести число")
    exit()

# Проверка на физический минимум (ниже абсолютного нуля)
if celsius < -273.15:
    print("Ошибка: температура ниже абсолютного нуля")
    exit()

# Перевод в Фаренгейты и Кельвины
fahrenheit = celsius * 9 / 5 + 32
kelvin = celsius + 273.15

# Вывод результата
print(f"Температура в °F: {fahrenheit:.2f}")
print(f"Температура в K: {kelvin:.2f}")
